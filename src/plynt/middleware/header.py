"""Header injection middleware for Plynt transport chains (ADR-0015).

Provides ``HeaderMiddleware`` and ``AsyncHeaderMiddleware``, which inject
static or dynamically generated headers on every outgoing request.

Typical uses:

- Fixed ``User-Agent`` string across all requests.
- Per-request correlation ID (``X-Correlation-ID``) generated by a callable.
- Simple API key auth (``X-Api-Key``) without a dedicated auth middleware.

**Non-overwrite guarantee:** headers already set on the ``Request`` object
are never overwritten, allowing per-request overrides.

**Chain position (ADR-0015):**
Place before ``AuthMiddleware`` so correlation IDs are uniform across all
retry attempts and ``Authorization`` is never at risk of being overwritten::

    middlewares = [
        CacheMiddleware(...),
        HeaderMiddleware({"User-Agent": "my-svc/1.0",
                          "X-Correlation-ID": lambda: str(uuid.uuid4())}),
        OAuth2AuthMiddleware(...),
        RetryMiddleware(...),
    ]

Usage::

    from plynt.middleware.header import HeaderMiddleware
    from plynt.http.transport import HttpxSyncTransport

    transport = HttpxSyncTransport(
        middlewares=[
            HeaderMiddleware({
                "User-Agent": "my-service/1.0",
                "X-Correlation-ID": lambda: str(uuid.uuid4()),
            }),
        ]
    )

"""

from __future__ import annotations

from collections.abc import Awaitable, Callable

from plynt.base.middleware import AsyncMiddleware, SyncMiddleware
from plynt.base.request import Request
from plynt.base.request_id import RequestIDPolicy, get_request_id
from plynt.base.response import Response

__all__ = ["AsyncHeaderMiddleware", "HeaderMiddleware"]

#: Type alias for a header value: either a static string or a zero-argument
#: callable that returns a string (evaluated once per request).
HeaderValue = str | Callable[[], str]


def _propagate_request_id(request: Request, policy: RequestIDPolicy | None) -> None:
    """Add the active ID only when its header is absent (ADR-0040)"""
    if policy is None:
        return
    request_id = get_request_id()
    if request_id is not None and not any(
        name.lower() == policy.header_name.lower() for name in request.headers
    ):
        request.headers[policy.header_name] = request_id


class HeaderMiddleware(SyncMiddleware):
    """Synchronous middleware that injects headers on every outgoing request.

    Values may be static strings or zero-argument callables. Callables are
    evaluated once per ``handle()`` call, making them suitable for generated
    values such as correlation IDs.

    Headers already present on the ``Request`` are **not overwritten**,
    so callers can pin individual headers by setting them in ``Request.headers``
    before the transport chain runs.

    Args:
        headers: Mapping of header names to static values or callables.
        request_id_policy: Enable propagation of the active request ID using
            this policy's header name. No header is added outside a scope.

    Example::

        import uuid
        from plynt.middleware.header import HeaderMiddleware

        mw = HeaderMiddleware({
            "User-Agent": "my-service/1.0",
            "X-Correlation-ID": lambda: str(uuid.uuid4()),
        })

    """

    def __init__(
        self,
        headers: dict[str, HeaderValue],
        *,
        request_id_policy: RequestIDPolicy | None = None,
    ) -> None:
        """Initialize HeaderMiddleware."""
        self._headers = headers
        self._request_id_policy = request_id_policy

    def handle(
        self,
        request: Request,
        next_handler: Callable[[Request], Response],
    ) -> Response:
        """Inject configured headers then delegate to the next handler.

        Headers already present on ``request`` are not overwritten.

        Args:
            request: The outgoing request, mutated in-place.
            next_handler: The next callable in the middleware chain.

        """
        for name, value in self._headers.items():
            if name not in request.headers:
                request.headers[name] = value() if callable(value) else value
        _propagate_request_id(request, self._request_id_policy)
        return next_handler(request)


class AsyncHeaderMiddleware(AsyncMiddleware):
    """Asynchronous counterpart of ``HeaderMiddleware``.

    Identical semantics: static strings are injected directly; callables are
    called (synchronously) once per request. Headers already present are not
    overwritten.

    Args:
        headers: Mapping of header names to static values or callables.
        request_id_policy: Enable propagation of the active request ID using
            this policy's header name. No header is added outside a scope.

    Example::

        import uuid
        from plynt.middleware.header import AsyncHeaderMiddleware

        mw = AsyncHeaderMiddleware({
            "User-Agent": "my-service/1.0",
            "X-Correlation-ID": lambda: str(uuid.uuid4()),
        })

    """

    def __init__(
        self,
        headers: dict[str, HeaderValue],
        *,
        request_id_policy: RequestIDPolicy | None = None,
    ) -> None:
        """Initialize AsyncHeaderMiddleware."""
        self._headers = headers
        self._request_id_policy = request_id_policy

    async def handle(
        self,
        request: Request,
        next_handler: Callable[[Request], Awaitable[Response]],
    ) -> Response:
        """Inject configured headers then delegate to the next handler.

        Args:
            request: The outgoing request, mutated in-place.
            next_handler: The next async callable in the middleware chain.

        """
        for name, value in self._headers.items():
            if name not in request.headers:
                request.headers[name] = value() if callable(value) else value
        _propagate_request_id(request, self._request_id_policy)
        return await next_handler(request)
